"""R3 — actual culturally mediated vocal coordination changes expressive capacity.

This is NOT a theory of language acquisition. In the original sourcefree
organism maturation gives an age-conditioned ceiling but no acquired ability
to emit an eligible SPEAK. The missing social relation is supplied by actual
independently answered SIGNAL→SPEAK encounters, preceded by the learner
personally hearing the same adult perform speech about an actual material
object. Two encounters separated by elapsed bodily maturation can support
one small actor-owned, reversible-in-future learning approximation.

Neither lexical tokens, syntax, fluent speech, caregiver benevolence nor
the adult's private communicative intention are generated by this mechanism.
"""
from .types import stable_id, copy, GRADE
from .organism import eligible
import math

STRENGTH_PER_PRACTICED_PAIR=.07
MIN_MATURATION_AGE_DAYS=180
MIN_AGE_GAP_DAYS=7


def conserve_reciprocated_vocal_turn(actor,experience,event_ref):
    if (experience.get("actor")!=actor.get("id") or
            type(event_ref) is not str or not event_ref):
        raise ValueError("VOCAL_FOREIGN_EVENT")
    if (experience.get("own_action")!="SIGNAL"
            or experience.get("status")!="PERFORMED"
            or experience.get("participated") is not True
            or (experience.get("felt_enactment") or {}).get(
                "attempted_operation")!="SIGNAL"):
        return None
    signs=[c for c in experience.get("perceived_cues",[])
           if type(c) is dict and c.get("kind")=="performed_signal"
           and c.get("actual_independent_speech_response") is True
           and c.get("source_actor")==actor["id"]
           and c.get("modality")=="auditory"
           and type(c.get("actor_accessible_speech_responder_ref")) is str
           and type(c.get("id")) is str]
    if len(signs)!=1:return None
    cue=signs[0];other=cue["actor_accessible_speech_responder_ref"]
    if other==actor["id"]:return None
    # Speech by an adult to which the child was never previously exposed
    # cannot be magically remembered. Prior material signs ground the
    # particular social source without granting comprehension of its words.
    demos=[d for d in actor.get("cultural_demonstrations",[])
           if d.get("heard_source_actor")==other
           and type(d.get("clock")) is int
           and type(experience.get("clock")) is int
           and d["clock"]<experience["clock"]]
    if not demos:return None
    earliest=max(demos,key=lambda x:(x["clock"],x["id"]))
    age=actor.get("age_days")
    if type(age) is not int or age<0:
        raise ValueError("VOCAL_INVALID_AGE")
    ident=stable_id("social_vocal_turn",{"actor":actor["id"],
        "event":event_ref,"sign":cue["id"],"other":other})
    rows=actor.setdefault("vocal_turn_experiences",[])
    if any(row.get("id")==ident for row in rows):
        raise ValueError("VOCAL_DUPLICATE_ACTOR_TURN")
    record={
        "id":ident,"actor":actor["id"],"event_ref":event_ref,
        "experience_ref":experience["ref"],
        "clock":experience["clock"],"age_days":age,
        "independently_responding_other_ref":other,
        "personally_received_response_sign_ref":cue["id"],
        "prior_public_object_speech_ref":earliest["id"],
        "originating_demonstration_event_ref":earliest["event_ref"],
        "childs_own_attempted_operation":"SIGNAL",
        "objective_response_not_actor_knowledge":True,
        "no_received_lexical_content":True,
        "not_an_assumption_about_other_motive":True,
        "grade":GRADE}
    rows.append(record)
    return record


def possible_vocal_coordination(actor,experience,event_ref):
    if experience.get("actor")!=actor.get("id"):return []
    if actor.get("role")!="child":return []
    age=actor.get("age_days")
    if type(age) is not int or age<MIN_MATURATION_AGE_DAYS:
        return []
    rows=actor.get("vocal_turn_experiences",[])
    current=[v for v in rows if v.get("event_ref")==event_ref
             and v.get("experience_ref")==experience.get("ref")]
    if len(current)!=1:return []
    cur=current[0]
    prior=[v for v in rows
           if v.get("actor")==actor["id"]
           and v.get("event_ref")!=event_ref
           and v.get("independently_responding_other_ref")==(
               cur["independently_responding_other_ref"])
           and type(v.get("clock")) is int
           and v["clock"]<cur["clock"]
           and type(v.get("age_days")) is int
           and cur["age_days"]-v["age_days"]>=MIN_AGE_GAP_DAYS]
    if not prior:return []
    prior=max(prior,key=lambda v:(v["clock"],v["id"]))
    body=actor.get("body",{})
    ceiling=body.get("language_ceiling")
    current_skill=body.get("language")
    if (type(ceiling) not in (float,int) or not math.isfinite(ceiling)
            or type(current_skill) not in (float,int)
            or not math.isfinite(current_skill)
            or ceiling<=current_skill or current_skill<0):
        return []
    gain=round(min(STRENGTH_PER_PRACTICED_PAIR,
                   ceiling-current_skill),5)
    if gain<=0:return []
    ident=stable_id("sourcequalified_vocal_coordination",{
        "actor":actor["id"],"earlier":prior["id"],"later":cur["id"]})
    if any(x.get("origin_later_turn_ref")==cur["id"] for x in
           actor.get("vocal_coordination_practices",[])):
        return []
    return [{
        "kind":"ACQUIRE_SOCIAL_VOCAL_COORDINATION",
        "practice_ref":ident,
        "earlier_actual_vocal_turn_ref":prior["id"],
        "later_actual_vocal_turn_ref":cur["id"],
        "source_other_ref":cur["independently_responding_other_ref"],
        "new_capacity_delta":gain,
        "not_a_learned_word_or_any_syntactic_skill":True,
        "maturation_ceiling_still_binds":True,
        "grade":GRADE}]


def admit_vocal_coordination(actor,experience,event_ref,proposal):
    matched=possible_vocal_coordination(actor,experience,event_ref)
    if len(matched)!=1:
        raise ValueError("VOCAL_NO_TWO_INDEPENDENT_SEPARATED_EXCHANGES")
    expected=matched[0]
    for k in ("practice_ref","earlier_actual_vocal_turn_ref",
              "later_actual_vocal_turn_ref","source_other_ref",
              "new_capacity_delta"):
        if proposal.get(k)!=expected[k]:
            raise ValueError("VOCAL_FORGED_SOURCE_OR_CAPACITY_"+k)
    b=actor["body"]
    original=b["language"]
    new=round(original+expected["new_capacity_delta"],5)
    if new>b["language_ceiling"]+1e-8:
        raise ValueError("VOCAL_CAPACITY_EXCEEDS_BODILY_MATURATION")
    b["language"]=new
    rec={
        "id":expected["practice_ref"],"actor":actor["id"],
        "origin_earlier_turn_ref":expected[
            "earlier_actual_vocal_turn_ref"],
        "origin_later_turn_ref":expected["later_actual_vocal_turn_ref"],
        "source_other_ref":expected["source_other_ref"],
        "origin_event":event_ref,
        "expressive_capacity_before":original,
        "expressive_capacity_after":new,
        "sourcefree_capacity_increment":expected["new_capacity_delta"],
        "no_word_semantics_or_syntactic_mastery_claim":True,
        "not_automatic_speech_eligibility":not eligible(b,"SPEAK")[0],
        "not_independent_scientific_maturation_law":True,
        "grade":GRADE}
    actor.setdefault("vocal_coordination_practices",[]).append(rec)
    return {"kind":proposal["kind"],"practice_ref":rec["id"],
            "status":"ACTUALLY_ACQUIRED_BOUNDED_SOCIAL_VOCAL_CAPACITY",
            "language_eligible_after_event":eligible(b,"SPEAK")[0],
            "grade":GRADE}
