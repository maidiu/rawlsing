"""R3 — actual culturally mediated vocal coordination changes expressive capacity.

This is NOT a theory of language acquisition. In the original sourcefree
organism maturation gives an age-conditioned ceiling but no acquired ability
to emit an eligible SPEAK. The missing social relation is supplied by actual
independently answered SIGNAL→SPEAK encounters, preceded by the learner
personally hearing the same adult perform speech about an actual material
object. Two encounters separated by elapsed bodily maturation can support
one small actor-owned, reversible-in-future learning approximation.

Neither lexical tokens, syntax, fluent speech, caregiver benevolence nor
the adult's private communicative intention are generated by this mechanism.
"""
from .types import stable_id, copy, GRADE
from .organism import eligible
from .mediated_efficacy import preproject_vocal_basis, preproject_exercise_basis
import math

STRENGTH_PER_PRACTICED_PAIR=.07
MIN_MATURATION_AGE_DAYS=180
MIN_AGE_GAP_DAYS=7


def conserve_reciprocated_vocal_turn(actor,experience,event_ref):
    if (experience.get("actor")!=actor.get("id") or
            type(event_ref) is not str or not event_ref):
        raise ValueError("VOCAL_FOREIGN_EVENT")
    if (experience.get("own_action")!="SIGNAL"
            or experience.get("status")!="PERFORMED"
            or experience.get("participated") is not True
            or (experience.get("felt_enactment") or {}).get(
                "attempted_operation")!="SIGNAL"):
        return None
    signs=[c for c in experience.get("perceived_cues",[])
           if type(c) is dict and c.get("kind")=="performed_signal"
           and c.get("actual_independent_speech_response") is True
           and c.get("source_actor")==actor["id"]
           and c.get("modality")=="auditory"
           and type(c.get("actor_accessible_speech_responder_ref")) is str
           and type(c.get("id")) is str]
    if len(signs)!=1:return None
    cue=signs[0];other=cue["actor_accessible_speech_responder_ref"]
    if other==actor["id"]:return None
    # Speech by an adult to which the child was never previously exposed
    # cannot be magically remembered. Prior material signs ground the
    # particular social source without granting comprehension of its words.
    demos=[d for d in actor.get("cultural_demonstrations",[])
           if d.get("heard_source_actor")==other
           and type(d.get("clock")) is int
           and type(experience.get("clock")) is int
           and d["clock"]<experience["clock"]]

    earliest=max(demos,key=lambda x:(x["clock"],x["id"])) if demos else None
    early=None
    if earliest is None:
        # New path: ordinary bodily participation -> independently addressed
        # trial -> actual responsive Other. No demonstration or lexical memory
        # is counterfeited when the social relation arises in ordinary activity.
        sel=experience.get("own_practical_selection") or {}
        if (sel.get("status")!="ACTOR_POLICY_PRACTICAL_ATTEMPT"
                or sel.get("actor")!=actor["id"]
                or sel.get("selected_project_refs")
                or sel.get("possible_end_trial")
                or sel.get("world_request",{}).get("addressed_party_ref")!=other):
            return None
        early=preproject_vocal_basis(actor,experience.get("location"),experience["clock"])
        if early is None:return None
    age=actor.get("age_days")
    if type(age) is not int or age<0:
        raise ValueError("VOCAL_INVALID_AGE")
    ident=stable_id("social_vocal_turn",{"actor":actor["id"],
        "event":event_ref,"sign":cue["id"],"other":other})
    rows=actor.setdefault("vocal_turn_experiences",[])
    if any(row.get("id")==ident for row in rows):
        raise ValueError("VOCAL_DUPLICATE_ACTOR_TURN")
    record={
        "id":ident,"actor":actor["id"],"event_ref":event_ref,
        "experience_ref":experience["ref"],
        "clock":experience["clock"],"age_days":age,
        **({"ordinary_location":experience["location"]} if early is not None else {}),
        "independently_responding_other_ref":other,
        "personally_received_response_sign_ref":cue["id"],
        **({"prior_public_object_speech_ref":earliest["id"],
            "originating_demonstration_event_ref":earliest["event_ref"]}
           if earliest is not None else {
            "ordinary_preproject_vocal_basis_ref":early["id"],
            "originating_own_vocal_event_ref":early["anchor_actual_event_ref"],
            "source_route":"ORDINARY_ACTOR_ADDRESSED_RESPONSIVE_LIFE"}),
        "childs_own_attempted_operation":"SIGNAL",
        "objective_response_not_actor_knowledge":True,
        "no_received_lexical_content":True,
        "not_an_assumption_about_other_motive":True,
        "grade":GRADE}
    rows.append(record)
    return record


def possible_vocal_coordination(actor,experience,event_ref):
    if experience.get("actor")!=actor.get("id"):return []
    if actor.get("role")!="child":return []
    age=actor.get("age_days")
    if type(age) is not int or age<MIN_MATURATION_AGE_DAYS:
        return []
    rows=actor.get("vocal_turn_experiences",[])
    current=[v for v in rows if v.get("event_ref")==event_ref
             and v.get("experience_ref")==experience.get("ref")]
    if len(current)!=1:return []
    cur=current[0]
    prior=[v for v in rows
           if v.get("actor")==actor["id"]
           and v.get("event_ref")!=event_ref
           and (v.get("independently_responding_other_ref")==(
               cur["independently_responding_other_ref"])
               or (cur.get("ordinary_preproject_vocal_basis_ref")
                   and v.get("ordinary_preproject_vocal_basis_ref")))
           and type(v.get("clock")) is int
           and v["clock"]<cur["clock"]
           and type(v.get("age_days")) is int]
    ordinary=cur.get("ordinary_preproject_vocal_basis_ref") is not None
    if ordinary:
        # Both ordinary turns need their own prior qualified participation.
        # Do not harvest the same age gap by alternating adult responders.
        prior=[v for v in prior if v.get("ordinary_preproject_vocal_basis_ref")]
        all_earlier=[v for v in rows if v.get("actor")==actor["id"]
                     and type(v.get("clock")) is int and v["clock"]<cur["clock"]
                     and type(v.get("age_days")) is int]
        if all_earlier and cur["age_days"]-max(v["age_days"] for v in all_earlier)<MIN_AGE_GAP_DAYS:
            return []
    if not prior:return []
    prior=max(prior,key=lambda v:(v["clock"],v["id"]))
    # A new turn every minute must not repeatedly reuse a much older
    # demonstration to harvest development. The IMMEDIATELY preceding
    # relevant turn must itself be separated by embodied lived days.
    if cur["age_days"]-prior["age_days"]<MIN_AGE_GAP_DAYS:
        return []
    body=actor.get("body",{})
    ceiling=body.get("language_ceiling")
    current_skill=body.get("language")
    if (type(ceiling) not in (float,int) or not math.isfinite(ceiling)
            or type(current_skill) not in (float,int)
            or not math.isfinite(current_skill)
            or ceiling<=current_skill or current_skill<0):
        return []
    gain=round(min(STRENGTH_PER_PRACTICED_PAIR,
                   ceiling-current_skill),5)
    if gain<=0:return []
    ident=stable_id("sourcequalified_vocal_coordination",{
        "actor":actor["id"],"earlier":prior["id"],"later":cur["id"]})
    if any(x.get("origin_later_turn_ref")==cur["id"] for x in
           actor.get("vocal_coordination_practices",[])):
        return []
    return [{
        "kind":"ACQUIRE_SOCIAL_VOCAL_COORDINATION",
        "practice_ref":ident,
        "earlier_actual_vocal_turn_ref":prior["id"],
        "later_actual_vocal_turn_ref":cur["id"],
        "source_other_ref":cur["independently_responding_other_ref"],
        **({"earlier_source_other_ref":prior["independently_responding_other_ref"],
            "ordinary_basis_refs":[prior["ordinary_preproject_vocal_basis_ref"],
                                   cur["ordinary_preproject_vocal_basis_ref"]],
            "source_route":"ORDINARY_ACTOR_ADDRESSED_RESPONSIVE_LIFE"}
           if ordinary else {}),
        "new_capacity_delta":gain,
        "not_a_learned_word_or_any_syntactic_skill":True,
        "maturation_ceiling_still_binds":True,
        "grade":GRADE}]


def admit_vocal_coordination(actor,experience,event_ref,proposal):
    matched=possible_vocal_coordination(actor,experience,event_ref)
    if len(matched)!=1:
        raise ValueError("VOCAL_NO_TWO_INDEPENDENT_SEPARATED_EXCHANGES")
    expected=matched[0]
    for k in ("practice_ref","earlier_actual_vocal_turn_ref",
              "later_actual_vocal_turn_ref","source_other_ref",
              "new_capacity_delta","earlier_source_other_ref",
              "ordinary_basis_refs","source_route"):
        if proposal.get(k)!=expected.get(k):
            raise ValueError("VOCAL_FORGED_SOURCE_OR_CAPACITY_"+k)
    b=actor["body"]
    original=b["language"]
    new=round(original+expected["new_capacity_delta"],5)
    if new>b["language_ceiling"]+1e-8:
        raise ValueError("VOCAL_CAPACITY_EXCEEDS_BODILY_MATURATION")
    b["language"]=new
    rec={
        "id":expected["practice_ref"],"actor":actor["id"],
        "origin_earlier_turn_ref":expected[
            "earlier_actual_vocal_turn_ref"],
        "origin_later_turn_ref":expected["later_actual_vocal_turn_ref"],
        "source_other_ref":expected["source_other_ref"],
        **({k:copy(expected[k]) for k in ("earlier_source_other_ref",
             "ordinary_basis_refs","source_route")} if "source_route" in expected else {}),
        "origin_event":event_ref,
        "expressive_capacity_before":original,
        "expressive_capacity_after":new,
        "sourcefree_capacity_increment":expected["new_capacity_delta"],
        "no_word_semantics_or_syntactic_mastery_claim":True,
        "not_automatic_speech_eligibility":not eligible(b,"SPEAK")[0],
        "not_independent_scientific_maturation_law":True,
        "grade":GRADE}
    actor.setdefault("vocal_coordination_practices",[]).append(rec)
    return {"kind":proposal["kind"],"practice_ref":rec["id"],
            "status":"ACTUALLY_ACQUIRED_BOUNDED_SOCIAL_VOCAL_CAPACITY",
            "language_eligible_after_event":eligible(b,"SPEAK")[0],
            "grade":GRADE}


def ordinary_expressive_opportunity(constitution,access):
    """Actually acquired vocal coordination is now recruited into expression.

    The prior responder must be present, but need not participate again.
    The operation is bodily/public SPEAK, not a lexical realization or a
    proposition. A model remains free to select another act or no act.
    """
    if (constitution.actor!=access.actor or constitution.role!='child'
            or not eligible(constitution.body,'SPEAK')[0]):
        return None
    present={c.get('source_actor') for c in access.cues
             if c.get('kind')=='coactor_present'}
    turns={v['id']:v for v in constitution.vocal_turn_experiences
           if v.get('actor')==constitution.actor and type(v.get('id')) is str}
    own={'id':constitution.actor,'role':constitution.role,
         'practice_exposures':constitution.practice_exposures,
         'power_exercises':constitution.power_exercises,
         'evidence_paths':constitution.evidence_paths}
    early=preproject_vocal_basis(own,access.location,access.world_clock)
    if early is None:return None
    for acquired in reversed(constitution.vocal_coordination_practices):
        if (acquired.get('actor')!=constitution.actor
                or acquired.get('source_route')!='ORDINARY_ACTOR_ADDRESSED_RESPONSIVE_LIFE'):
            continue
        a=turns.get(acquired.get('origin_earlier_turn_ref'))
        b=turns.get(acquired.get('origin_later_turn_ref'))
        if (a is None or b is None or a.get('event_ref')==b.get('event_ref')
                or acquired.get('origin_event')!=b.get('event_ref')
                or a.get('ordinary_location')!=access.location
                or b.get('ordinary_location')!=access.location
                or acquired.get('earlier_source_other_ref')!=a.get('independently_responding_other_ref')
                or acquired.get('source_other_ref')!=b.get('independently_responding_other_ref')
                or acquired.get('ordinary_basis_refs')!=[a.get('ordinary_preproject_vocal_basis_ref'),
                                                          b.get('ordinary_preproject_vocal_basis_ref')]
                or not present.intersection({acquired.get('source_other_ref'),
                                             acquired.get('earlier_source_other_ref')})
                or type(b.get('clock')) is not int or b['clock']>=access.world_clock
                or type(a.get('age_days')) is not int or type(b.get('age_days')) is not int
                or b['age_days']-a['age_days']<MIN_AGE_GAP_DAYS):
            continue
        return {'action':'SPEAK','score':.03,
                'basis':[a['experience_ref'],b['experience_ref']],
                'source_event_refs':[a['event_ref'],b['event_ref']],
                'source_aggregate_refs':list(dict.fromkeys(acquired['ordinary_basis_refs'])),
                'historical_support_statuses':['ACQUIRED_ORDINARY_SOCIAL_VOCAL_COORDINATION_NOT_WORDS'],
                'opportunity':'HISTORICALLY_MEDIATED_PUBLIC_VOCAL_EXPRESSION',
                'vocal_coordination_practice_ref':acquired['id'],
                'grade':GRADE}
    return None


def qualified_ordinary_vocal_ancestry(actor,location,clock):
    """Actual acquired coordination and its two personally lived sources.
    No present responder, desire, lexical competence or world right inferred.
    """
    if actor.get('role')!='child' or type(clock) is not int:return []
    aid=actor['id']
    def turn(ref):
        rows=[r for r in actor.get('vocal_turn_experiences',[])
              if r.get('id')==ref and r.get('actor')==aid
              and r.get('ordinary_location')==location
              and r.get('source_route')=='ORDINARY_ACTOR_ADDRESSED_RESPONSIVE_LIFE'
              and type(r.get('clock')) is int and r['clock']<clock
              and type(r.get('age_days')) is int]
        if len(rows)!=1:return None
        r=rows[0]
        sources=[q for q in actor.get('practice_exposures',[])
                 if q.get('id')==r.get('ordinary_preproject_vocal_basis_ref')
                 and q.get('actor')==aid and q.get('location')==location
                 and q.get('operation')=='SIGNAL'
                 and q.get('grade')=='SOURCEFREE_CONDITIONED_AGGREGATE_PRACTICE'
                 and type(q.get('end_clock')) is int and q['end_clock']<=r['clock']
                 and type(q.get('modeled_practice_hours')) in (int,float)
                 and 0<q['modeled_practice_hours']<=3650*16
                 and q.get('anchor_actual_event_ref')==r.get('originating_own_vocal_event_ref')
                 and preproject_exercise_basis(actor,'SIGNAL',location,
                          q.get('preproject_exercise_ref'),q.get('start_clock'))]
        paths=[p for p in actor.get('evidence_paths',[])
               if p.get('event')==r.get('event_ref') and p.get('experience_ref')==r.get('experience_ref')
               and p.get('own_action')=='SIGNAL']
        return r if len(sources)==len(paths)==1 else None
    out=[]
    for p in actor.get('vocal_coordination_practices',[]):
        if p.get('actor')!=aid or p.get('source_route')!='ORDINARY_ACTOR_ADDRESSED_RESPONSIVE_LIFE':continue
        a=turn(p.get('origin_earlier_turn_ref'));b=turn(p.get('origin_later_turn_ref'))
        if (a is None or b is None or a['clock']>=b['clock'] or a['event_ref']==b['event_ref']
                or b['age_days']-a['age_days']<MIN_AGE_GAP_DAYS
                or p.get('origin_event')!=b['event_ref']
                or p.get('earlier_source_other_ref')!=a.get('independently_responding_other_ref')
                or p.get('source_other_ref')!=b.get('independently_responding_other_ref')
                or p.get('ordinary_basis_refs')!=[a['ordinary_preproject_vocal_basis_ref'],b['ordinary_preproject_vocal_basis_ref']]):continue
        out.append({'practice_ref':p['id'],'earlier_turn':a,'later_turn':b,
                    'ordinary_basis_refs':copy(p['ordinary_basis_refs'])})
    return out


def ordinary_vocal_actor_view(c):
    return {'id':c.actor,'role':c.role,'practice_exposures':c.practice_exposures,
            'power_exercises':c.power_exercises,'evidence_paths':c.evidence_paths,
            'vocal_turn_experiences':c.vocal_turn_experiences,
            'vocal_coordination_practices':c.vocal_coordination_practices}


def ordinary_vocal_self_exercise(c,access):
    """Acquired social power can become available for own unaddressed exercise."""
    if c.actor!=access.actor or not eligible(c.body,'SING')[0]:return None
    rows=qualified_ordinary_vocal_ancestry(ordinary_vocal_actor_view(c),access.location,access.world_clock)
    if not rows:return None
    r=rows[-1];a=r['earlier_turn'];b=r['later_turn']
    return {'action':'SING','score':.03,'basis':[a['experience_ref'],b['experience_ref']],
            'source_event_refs':[a['event_ref'],b['event_ref']],
            'source_aggregate_refs':list(dict.fromkeys(r['ordinary_basis_refs'])),
            'historical_support_statuses':['ACQUIRED_SOCIAL_VOCAL_POWER_AVAILABLE_FOR_OWN_EXPLORATION'],
            'opportunity':'SOCIALLY_CONSTITUTED_SOLO_VOCAL_EXERCISE_NOT_MOTIVE',
            'vocal_coordination_practice_ref':r['practice_ref'],'grade':GRADE}


def ordinary_vocal_basis_still_qualified(actor,basis,location,clock):
    if basis.get('location')!=location:return False
    return any(x['practice_ref']==basis.get('vocal_coordination_practice_ref')
               and x['earlier_turn']['id']==basis.get('earlier_response_turn_ref')
               and x['later_turn']['id']==basis.get('later_response_turn_ref')
               and x['ordinary_basis_refs']==basis.get('ordinary_basis_refs')
               for x in qualified_ordinary_vocal_ancestry(actor,location,clock))
