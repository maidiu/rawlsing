def validate_required_columns(frame: pd.DataFrame, required_columns: list[str], name: str) -> list[str]:
    errors: list[str] = []
    missing = [column for column in required_columns if column not in frame.columns]
    if missing:
        errors.append(f"{name}: missing columns {missing}")
    return errors


def validate_forbidden_runtime_claims(frame: pd.DataFrame) -> list[str]:
    errors: list[str] = []
    if frame.empty:
        return errors
    for column in ("runtime_safe_for_app", "ready_for_runtime_consumption"):
        if column in frame.columns and frame[column].astype(str).str.lower().eq("true").any():
            errors.append(f"forbidden runtime claim leaked in {column}")
    return errors


