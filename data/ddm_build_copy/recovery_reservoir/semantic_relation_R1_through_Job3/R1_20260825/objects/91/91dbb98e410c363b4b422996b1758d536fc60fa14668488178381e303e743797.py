import pandas as pd, json, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def check(name,cond,detail=None): checks.append({'check':name,'pass':bool(cond),'detail':detail})
status=json.load(open(ROOT/'CURRENT_STATUS_R4.json'))
can=pd.read_csv(ROOT/'PROVENANCE/SEALED_R6_T08_CANARY_RECOVERY_R4.csv')
r6=pd.read_csv(ROOT/'PROVENANCE/R6_T08_SEALED_PARENT_ROWS_R4.csv')
r14idx=pd.read_csv(ROOT/'PROVENANCE/R14_ACCEPTED_SOURCE_OBJECT_INDEX_R4.csv')
r14=pd.read_csv(ROOT/'NARROWING/T08_R14_SOURCE_NATIVE_OBJECT_DISPOSITION_R4.csv')
proxy=pd.read_csv(ROOT/'AUDIT/O11_T08_139_PROXY_GROUP_DISPOSITION_R4.csv')
onto=pd.read_csv(ROOT/'NARROWING/T08_INSTITUTION_CLASS_ONTOLOGY_R4.csv')
mapd=pd.read_csv(ROOT/'NARROWING/T08_INSTITUTION_CLASS_MAPPING_R4.csv',low_memory=False)
cross=pd.read_csv(ROOT/'NARROWING/T08_CROSS_OBJECT_SAME_PREDICATE_RECALL_R4.csv')
pk=pd.read_csv(ROOT/'NARROWING/T08_CANONICAL_REVIEW_PACKETS_R4.csv')
check('r6_parent_t08_20',len(r6)==20,len(r6))
check('r6_canary_rows_20',len(can)==20,len(can))
check('r6_all_relation_ids_exact',set(can.relation_authority_id)==set(r6.relation_authority_id))
check('r6_all_exact_implementation_members_resolved',(can.resolved_member_count==can.member_count).all())
check('r6_all_canaries_accounted',can.canary_recovery_status.str.startswith('RECOVERED_R6_T08_RELATION').all(),can.canary_recovery_status.value_counts().to_dict())
check('r6_boundary_reviews_2',(can.canary_recovery_status=='RECOVERED_R6_T08_RELATION__MEMBER_BOUNDARY_REVIEW').sum()==2)
check('r6_upstream_semantic_gap_1',(can.canary_recovery_status=='RECOVERED_R6_T08_RELATION__UPSTREAM_SEMANTIC_GAP_EXPLICIT').sum()==1)
check('r14_parent_accepted_548',len(r14idx)==548,len(r14idx))
check('r14_disposition_ledger_548',len(r14)==548,len(r14))
check('r14_all_parent_ids_accounted',set(r14.r14_object_id)==set(r14idx.object_id))
check('r14_no_empty_disposition',r14.disposition.fillna('').ne('').all())
check('r14_known_r6_or_alias_16',(r14.disposition=='KNOWN_R6_T08_SOURCE_OBJECT_OR_ALIAS__NO_NEW_ADJUDICATION').sum()==16)
check('r14_novel_exact_review_1',(r14.disposition=='EMIT_T08_SOURCE_OBJECT_REVIEW_CANDIDATE').sum()==1)
check('o11_proxy_exact_139',len(proxy)==139,len(proxy))
check('o11_proxy_all_dispositioned',proxy.disposition.fillna('').ne('').all())
check('ontology_9_classes',len(onto)==9,len(onto))
check('ontology_unique',onto.institution_class.is_unique)
check('mapping_sem_units_unique',mapd.sem__audit_unit_id.is_unique)
check('cross_groups_42',len(cross)==42,len(cross))
check('cross_review_groups_34',(cross.disposition=='EMIT_CROSS_OBJECT_T08_RECALL_HYPEREDGE').sum()==34)
check('packets_25',len(pk)==25,len(pk))
check('packets_source_1',(pk.packet_type=='SOURCE_NATIVE_MULTICLASS').sum()==1)
check('packets_cross_24',(pk.packet_type=='CROSS_OBJECT_SAME_PREDICATE_RECALL').sum()==24)
check('packets_no_accept_authority',not pk.status.astype(str).str.contains('ACCEPT|AUTHORITY',case=False,regex=True).any())
check('job3_blocked',status.get('job3_authorized') is False)
check('811_not_complete',status.get('o12_r2_811_complete_authority') is False)
check('next_t09',status.get('t08',{}).get('next_dependency')=='T09 reciprocal roles')
errors=[c for c in checks if not c['pass']]
out={'validator':'validate_t08_checkpoint_r4.py','status':'PASS' if not errors else 'FAIL','checks':len(checks),'errors':len(errors),'details':checks}
json.dump(out,open(ROOT/'VALIDATION/VALIDATION_RESULT_R4.json','w'),indent=2)
print(json.dumps({'status':out['status'],'checks':len(checks),'errors':len(errors)},indent=2))
if errors:
 print(json.dumps(errors,indent=2)); sys.exit(1)
